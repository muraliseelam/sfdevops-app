def fls_fields(obj, spec):
    """Fields that can carry FLS: not required, not master-detail (Name is not listed)."""
    out = []
    for fname, f in (spec.get('fields') or {}).items():
        if f.get('required') or f['type'] == 'MasterDetail':
            continue
        out.append(f'{obj}.{fname}')
    return out


def permission_set_xml(name, ps, objects, settings):
    object_perms = ps['objects'](objects)
    unknown = [o for o in object_perms if o not in objects]
    if unknown:
        raise ModelError(f'{name}: objects not in objects.yml: {unknown}')
    for setting in ps.get('custom_settings', []):
        if setting not in settings:
            raise ModelError(f'{name}: custom setting {setting} is not in objects.yml')
    if len(ps['description']) > 255:
        raise ModelError(f'{name}: description is longer than 255 characters')

    c = []
    if ps.get('app'):
        c.append(('applicationVisibilities', [('application', APP), ('visible', True)]))
    for cls in sorted(set(ps.get('classes', []))):
        c.append(('classAccesses', [('apexClass', cls), ('enabled', True)]))
    for perm in sorted(ps.get('custom_permissions', [])):
        c.append(('customPermissions', [('enabled', True), ('name', perm)]))
    for setting in sorted(ps.get('custom_settings', [])):
        c.append(('customSettingAccesses', [('enabled', True), ('name', setting)]))
    c.append(('description', ps['description']))
    if ps.get('external_principal'):
        c.append(('externalCredentialPrincipalAccesses', [
            ('enabled', True), ('externalCredentialPrincipal', GITHUB_PRINCIPAL)]))
    editable = ps['fls'] == 'edit'
    for obj in sorted(object_perms):
        for field in sorted(fls_fields(obj, objects[obj])):
            c.append(('fieldPermissions', [
                ('editable', editable), ('field', field), ('readable', True)]))
    c.append(('hasActivationRequired', False))
    c.append(('label', ps['label']))
    for obj in sorted(object_perms):
        create, read, edit, delete, view_all = object_perms[obj]
        c.append(('objectPermissions', [
            ('allowCreate', create),
            ('allowDelete', delete),
            ('allowEdit', edit),
            ('allowRead', read),
            ('modifyAllRecords', False),
            ('object', obj),
            ('viewAllRecords', view_all),
        ]))
    for tab in ps.get('tabs', []):
        c.append(('tabSettings', [('tab', tab), ('visibility', 'Visible')]))
    return xml_document('PermissionSet', c, MARKER, NOTE)


def build(objects, settings):
    return {f'permissionsets/{name}.permissionset-meta.xml':
            permission_set_xml(name, ps, objects, settings)
            for name, ps in PERMISSION_SETS.items()}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--check', action='store_true',
                    help='write nothing; exit 1 if any generated file is missing, stale or orphaned')
    ap.add_argument('--no-prune', action='store_true',
                    help='keep generated permission sets that are no longer defined here')
    args = ap.parse_args(argv)
    try:
        objects, settings = load_model()
        files = build(objects, settings)
    except ModelError as exc:
        print(exc, file=sys.stderr)
        return 2
    written, unchanged, pruned = sync(files, OUT_DIR, ('permissionsets',), MARKER,
                                      check=args.check, prune=not args.no_prune)
    verb = 'would write' if args.check else 'wrote'
    for rel in written:
        print(f'{verb}: {rel}')
    for rel in pruned:
        print(f'{"would prune" if args.check else "pruned"}: {rel}')
    print(f'{len(files)} permission sets: {len(written)} {verb}, {len(unchanged)} unchanged, '
          f'{len(pruned)} pruned.')
    if args.check and (written or pruned):
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())

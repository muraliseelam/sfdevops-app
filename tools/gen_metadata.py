#!/usr/bin/env python3
"""Generate the hub's object metadata from tools/objects.yml.

    py tools/gen_metadata.py            # write the generated files
    py tools/gen_metadata.py --check    # exit 1 if any generated file is missing or stale
    py tools/gen_metadata.py --no-prune # keep generated files that objects.yml no longer produces

Writes, under sfdevops-app/main/default/:
    objects/<Obj>/<Obj>.object-meta.xml             every custom object and the custom setting
    objects/<Obj>/fields/<Field>.field-meta.xml     every field
    objects/<Obj>/listViews/All.listView-meta.xml   every custom object
    objects/<Obj>/validationRules/Append_Only...    objects marked append_only: true
    layouts/<Obj>-<Label> Layout.layout-meta.xml    every custom object (not the custom setting)
    tabs/<Obj>.tab-meta.xml                         the objects listed in OBJECT_TABS

Every generated file carries the MARKER comment. The generator only ever rewrites or prunes
files that carry it, so hand-authored files in the same folders (the flexipage tabs, for
example) are never touched. Files are rewritten only when their content changes.

Element order matters to the Metadata API ("Element ... invalid at this location"), so every
element list below is written in the WSDL order, which is alphabetical with fullName first.
"""
import argparse
import os
import sys
from pathlib import Path
from xml.sax.saxutils import escape

import yaml

HUB_ROOT = Path(__file__).resolve().parent.parent
OBJECTS_YML = HUB_ROOT / 'tools' / 'objects.yml'
OUT_DIR = HUB_ROOT / 'sfdevops-app' / 'main' / 'default'
NS = 'http://soap.sforce.com/2006/04/metadata'
MARKER = 'Generated by tools/gen_metadata.py from tools/objects.yml'

# ---- Presentation config (UI, not data model) ---------------------------------------------

